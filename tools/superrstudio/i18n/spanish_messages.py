# Generates the Spanish implementations of SuperRStudio's message interfaces.
# SPDX-License-Identifier: AGPL-3.0-only
#
#   python tools/superrstudio/i18n/spanish_messages.py
#
# RStudio's GWT build compiles only the locales for which every upstream
# message interface has resources (en, fr). Instead of an "es" GWT locale,
# SuperRStudio features choose their language at run time from the
# user-interface language preference (SuperRStudioLanguage.java). For each
# interface below, this script reads the English @DefaultMessage annotations
# and the Spanish XxxMessages_es.properties and writes XxxMessagesEs.java,
# a plain class implementing the interface. Non-ASCII characters are written
# as \uXXXX escapes so the generated source does not depend on the compiler's
# file encoding. Keys without a Spanish text keep the English text and are
# reported; the script fails if a Spanish key has no English method or the
# placeholders differ.
import os
import re
import sys

here = os.path.dirname(os.path.abspath(__file__))
folder = os.path.normpath(os.path.join(
    here, '..', '..', '..', 'src/gwt/src/org/rstudio/studio/client/workbench/views/superrstudio'))
INTERFACES = ['ScatterMessages', 'LfqMessages', 'DependencyMessages']

METHOD = re.compile(r'@DefaultMessage\("((?:[^"\\]|\\.)*)"\)\s*String\s+(\w+)\s*\(([^)]*)\)\s*;')


def unescape_java(text):
    return re.sub(r'\\(.)', lambda m: {'n': '\n', 't': '\t'}.get(m.group(1), m.group(1)), text)


def java_literal(text):
    out = []
    for ch in text:
        if ch == '\\':
            out.append('\\\\')
        elif ch == '"':
            out.append('\\"')
        elif ch == '\n':
            out.append('\\n')
        elif ord(ch) < 32 or ord(ch) > 126:
            out.append('\\u%04x' % ord(ch))
        else:
            out.append(ch)
    return '"' + ''.join(out) + '"'


def placeholders(text):
    return sorted(set(re.findall(r'\{(\d+)\}', text)))


def message_format(text):
    # java.text.MessageFormat quoting as used in these files: '' is one quote
    return text.replace("''", "'")


def read_properties(path):
    values = {}
    with open(path, encoding='utf-8') as handle:
        for line in handle:
            line = line.rstrip('\n')
            if not line or line.startswith('#'):
                continue
            key, _, value = line.partition('=')
            values[key.strip()] = value
    return values


def generate(name):
    source = open(os.path.join(folder, name + '.java'), encoding='utf-8').read()
    methods = METHOD.findall(source)
    if not methods:
        sys.exit('no messages found in ' + name)
    spanish = read_properties(os.path.join(folder, name + '_es.properties'))
    keys = [key for _, key, _ in methods]
    unknown = sorted(set(spanish) - set(keys))
    if unknown:
        sys.exit('%s_es.properties has keys without a method: %s' % (name, ', '.join(unknown)))
    lines = ['// Generated by tools/superrstudio/i18n/spanish_messages.py from %s_es.properties.' % name,
             '// SPDX-License-Identifier: AGPL-3.0-only. Do not edit; regenerate instead.',
             'package org.rstudio.studio.client.workbench.views.superrstudio;',
             '',
             '// Spanish (Latin American usage) texts for %s; see SuperRStudioLanguage.' % name,
             'public class %sEs implements %s' % (name, name),
             '{']
    missing = []
    for english, key, params in methods:
        english = message_format(unescape_java(english))
        text = spanish.get(key)
        if text is None:
            missing.append(key)
            text = english
        else:
            text = message_format(text)
        if placeholders(text) != placeholders(english):
            sys.exit('%s.%s: placeholders differ between English and Spanish' % (name, key))
        args = [p.strip().split() for p in params.split(',') if p.strip()]
        signature = ', '.join('%s %s' % (kind, var) for kind, var in args)
        values = ', '.join(var if kind == 'String' else 'String.valueOf(%s)' % var for kind, var in args)
        body = ('return SuperRStudioLanguage.format(%s, %s);' % (java_literal(text), values)
                if args else 'return %s;' % java_literal(text))
        lines.append('   @Override public String %s(%s) { %s }' % (key, signature, body))
    lines.append('}')
    target = os.path.join(folder, name + 'Es.java')
    with open(target, 'w', encoding='utf-8', newline='\n') as handle:
        handle.write('\n'.join(lines) + '\n')
    print('%s: %d messages, %d without Spanish text%s' % (
        name, len(methods), len(missing), (' (' + ', '.join(missing) + ')') if missing else ''))


for interface in INTERFACES:
    generate(interface)
